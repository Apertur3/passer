// M07 Apollonian gasket under a Mobius motion of the disc.
// One rule: in the gap between any three mutually tangent circles there is exactly one more (Descartes), so fill every gap forever; then move the whole packing by a disc automorphism, which sends circles to circles and keeps every tangency.
export const meta = {
  id: 'm07-apollonian', title: 'Apollonian gasket', T: 16, still: 0.3, start: 0.25, aspects: ['4:5', '16:9', '1:1'],
  math: 'k4 = k1 + k2 + k3 +- 2 sqrt(k1k2 + k2k3 + k3k1); circles move by z -> (z - a)/(1 - conj(a) z), a(theta) a closed orbit',
  label: 'An Apollonian gasket, the packing of tangent circles generated by Descartes\' theorem, swirled by a Mobius map that carries every circle to another exact circle and keeps all tangencies.',
  // kmax: smallest circle drawn has curvature kmax; swirl: size of the Mobius orbit a(theta)
  params: { kmax: 520, swirl: 0.22 },
};

const TAU = 2 * Math.PI, NB = 4, memo = {};
// ---- Descartes in augmented form: a circle is (k, k z). The circle in the gap opposite O_i is 2 (X + O_j + O_l) - O_i, for the curvature and for k z alike.
function build(kmax) {
  if (memo[kmax]) return memo[kmax];
  const K = [], WX = [], WY = [], DP = [], k3 = 1 + 2 / Math.sqrt(3), add = (k, x, y, d) => { K.push(k); WX.push(x); WY.push(y); DP.push(d); return K.length - 1; };
  // root quadruple: the unit circle (k = -1) and three equal circles tangent to it and to each other (three-fold symmetric)
  const cr = 1 / k3, dist = 1 - cr, q = [add(-1, 0, 0, 0)];
  for (let i = 0; i < 3; i++) { const a = TAU * i / 3 + Math.PI / 2; q.push(add(k3, k3 * dist * Math.cos(a), k3 * dist * Math.sin(a), 1)); }
  const st = []; // state: [X (newest), O1, O2, O3, depth]
  for (let i = 0; i < 4; i++) { const o = q.filter((_, j) => j !== i), s = o.reduce((a, b) => [a[0] + K[b], a[1] + WX[b], a[2] + WY[b]], [0, 0, 0]);
    const k = 2 * s[0] - K[q[i]]; if (k <= kmax) st.push([add(k, 2 * s[1] - WX[q[i]], 2 * s[2] - WY[q[i]], 1), ...o, 1]); }
  while (st.length) {
    const [x, a, b, c, d] = st.pop(), o = [a, b, c];
    for (let i = 0; i < 3; i++) { const j = o[(i + 1) % 3], l = o[(i + 2) % 3], oi = o[i];
      const k = 2 * (K[x] + K[j] + K[l]) - K[oi]; if (k > kmax) continue;
      const nx = add(k, 2 * (WX[x] + WX[j] + WX[l]) - WX[oi], 2 * (WY[x] + WY[j] + WY[l]) - WY[oi], d + 1); st.push([nx, x, j, l, d + 1]); }
  }
  const n = K.length, CX = new Float64Array(n), CY = new Float64Array(n), R = new Float64Array(n);
  for (let i = 0; i < n; i++) { CX[i] = WX[i] / K[i]; CY[i] = WY[i] / K[i]; R[i] = Math.abs(1 / K[i]); }
  return (memo[kmax] = { n, CX, CY, R, DP: Uint8Array.from(DP) });
}
const BUCKET = [0, 0, 0, 0].map(() => ({ f: new Float32Array(3 * 7000), n: 0 })), RING = [0, 0, 0, 0].map(() => ({ f: new Float32Array(3 * 9000), n: 0 }));
const dots = new Float32Array(3 * 7000);

export function draw(ctx, { g }) {
  const P = g.params, D = build(P.kmax), { n, CX, CY, R, DP } = D, rd = Math.min(g.bx, g.by);
  const v1 = g.voice(1), v2 = g.voice(2), v3 = g.voice(3), dr = g.drift;
  // the orbit a(theta): two closed circles; live mode lets the second one slip against the first, so the swirl never retraces
  const sw = P.swirl * (g.live ? 0.85 + 0.15 * Math.sin(dr * 0.04) : 1), ax = sw * (0.7 * Math.cos(v1) + 0.3 * Math.cos(-2 * v2 + 0.8)), ay = sw * (0.7 * Math.sin(v1) + 0.3 * Math.sin(-2 * v2 + 0.8));
  const rc = Math.cos(v1 / 3), rs = Math.sin(v1 / 3); // the packing is three-fold symmetric: one third of a turn per loop closes the loop
  const a2 = ax * ax + ay * ay, wave = v3; // depth ripple: line weight swells and travels inward
  for (const b of BUCKET) b.n = 0;
  for (const b of RING) b.n = 0;
  const flow = v2 / TAU; let nd = 0;
  for (let i = 1; i < n; i++) {
    // rotate the centre, then the image of circle |z - c| = r under w = (z - a)/(1 - conj(a) z): w0 = -conj(Z)/P, radius^2 = (|Z|^2 - P (|B|^2 - r^2)) / P^2
    const cx = CX[i] * rc - CY[i] * rs, cy = CX[i] * rs + CY[i] * rc, r = R[i], rr = r * r;
    // from |z - c| = r with z = (w + a)/(1 + conj(a) w): A = 1 - c conj(a), B = a - c
    const Ar = 1 - (cx * ax + cy * ay), Ai = -(cy * ax - cx * ay), Br = ax - cx, Bi = ay - cy, Pp = Ar * Ar + Ai * Ai - rr * a2;
    // Z = A conj(B) - r^2 conj(a)
    const Zr = Ar * Br + Ai * Bi - rr * ax, Zi = Ai * Br - Ar * Bi + rr * ay;
    const wx = -Zr / Pp, wy = Zi / Pp, rad2 = (Zr * Zr + Zi * Zi - Pp * (Br * Br + Bi * Bi - rr)) / (Pp * Pp), rad = Math.sqrt(Math.max(rad2, 0));
    const px = rad * rd; // radius in S
    if (px < 0.0016) continue;
    if (px < 0.0045) { if (nd < 7000) { dots[nd * 3] = wx * rd; dots[nd * 3 + 1] = wy * rd; dots[nd * 3 + 2] = Math.min(1, (px - 0.0016) / 0.0029); nd++; } continue; }
    if (px > 0.016) { // concentric rings inside a big circle: their images are the (non-concentric) circles of a Mobius-bent pencil, flowing inward
      const N = Math.min(7, Math.floor(px / 0.0085));
      for (let j = 0; j < N; j++) { const u = (((j / N + flow) % 1) + 1) % 1, f2 = (1 - 0.94 * u) * (1 - 0.94 * u) * rr;
        const P2 = Ar * Ar + Ai * Ai - f2 * a2, Z2r = Ar * Br + Ai * Bi - f2 * ax, Z2i = Ai * Br - Ar * Bi + f2 * ay, w2x = -Z2r / P2, w2y = Z2i / P2, r2 = Math.sqrt(Math.max(0, (Z2r * Z2r + Z2i * Z2i - P2 * (Br * Br + Bi * Bi - f2)) / (P2 * P2)));
        const rg = RING[Math.min(NB - 1, Math.floor(Math.sin(Math.PI * u) * NB * 0.999))]; if (rg.n < 9000) { rg.f[rg.n * 3] = w2x * rd; rg.f[rg.n * 3 + 1] = w2y * rd; rg.f[rg.n * 3 + 2] = r2 * rd; rg.n++; } }
    }
    const swell = 0.5 + 0.5 * Math.sin(wave - DP[i] * 0.55), al = 0.45 + 0.55 * swell, b = BUCKET[Math.min(NB - 1, Math.floor(al * NB))];
    if (b.n < 7000) { b.f[b.n * 3] = wx * rd; b.f[b.n * 3 + 1] = wy * rd; b.f[b.n * 3 + 2] = px; b.n++; }
  }
  for (let q = 0; q < NB; q++) {
    const b = BUCKET[q]; if (!b.n) continue;
    g.pen(ctx, q > 1 ? 'fine' : 'hair', 0.55 + 0.45 * (q + 1) / NB, g.c.ink); ctx.beginPath();
    for (let i = 0; i < b.n; i++) { ctx.moveTo(b.f[i * 3] + b.f[i * 3 + 2], b.f[i * 3 + 1]); ctx.arc(b.f[i * 3], b.f[i * 3 + 1], b.f[i * 3 + 2], 0, TAU); }
    ctx.stroke();
  }
  for (let q = 0; q < NB; q++) {
    const b = RING[q]; if (!b.n) continue;
    g.pen(ctx, 'hair', 0.3 + 0.6 * (q + 1) / NB, g.c.cool); ctx.beginPath();
    for (let i = 0; i < b.n; i++) { ctx.moveTo(b.f[i * 3] + b.f[i * 3 + 2], b.f[i * 3 + 1]); ctx.arc(b.f[i * 3], b.f[i * 3 + 1], b.f[i * 3 + 2], 0, TAU); }
    ctx.stroke();
  }
  ctx.fillStyle = g.c.ink; ctx.globalAlpha = 0.8; ctx.beginPath(); // the smallest circles, as dots
  for (let i = 0; i < nd; i++) { const rdot = 0.0016 + dots[i * 3 + 2] * 0.0012; ctx.moveTo(dots[i * 3] + rdot, dots[i * 3 + 1]); ctx.arc(dots[i * 3], dots[i * 3 + 1], rdot, 0, TAU); }
  ctx.fill(); ctx.globalAlpha = 1;
  g.pen(ctx, 'line', 1, g.c.ink); ctx.beginPath(); ctx.arc(0, 0, rd, 0, TAU); ctx.stroke();
}
